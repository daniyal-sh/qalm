// Writes the standalone brand SVGs from mark.mjs:  node assets/brand/build.mjs
// Each file is self-contained (no <use>, no CSS, no currentColor), so any consumer can inline it.
// It also refreshes MARK_SVG in apps/server/src/brand.ts (the worker can't read files, so the mark is inlined there).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { COLORS, iconSvg, markSvg } from './mark.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const NOTE =
  'qalm mark A, "nib in orbit". Generated by assets/brand/build.mjs from mark.mjs; edit those, not this file. ' +
  'No occluder: masks cut the back of the orbit inside the nib and the ring around the planet, so it works on any background.';

const pretty = (svg, note) => svg.replace(/^(<svg[^>]*>)/, `$1\n  <!-- ${note} -->\n  `).replace(/></g, '>\n  <').replace(/\n {2}<\/svg>$/, '\n</svg>\n')
  // keep <defs>/<mask> children on their own lines but don't indent the closing tags oddly
  .replace(/\n {2}<\/(defs|mask)>/g, '</$1>');

const files = {
  'qalm-mark.svg': [markSvg({ colors: COLORS.light }), `${NOTE} For light surfaces.`],
  'qalm-mark-dark.svg': [markSvg({ colors: COLORS.dark }), `${NOTE} For dark surfaces.`],
  'qalm-mark-small.svg': [markSvg({ colors: COLORS.light, weight: 'small' }), `${NOTE} Heavier weight for 24 px and below, light surfaces.`],
  'qalm-mark-small-dark.svg': [markSvg({ colors: COLORS.dark, weight: 'small' }), `${NOTE} Heavier weight for 24 px and below, dark surfaces.`],
  'qalm-icon.svg': [iconSvg(), 'qalm app icon: the graphite tile (#1c1c1f), full bleed and square (platforms round it), with the dark mark at 72%. Generated by assets/brand/build.mjs.'],
};
for (const [name, [svg, note]] of Object.entries(files)) {
  writeFileSync(join(here, name), pretty(svg, note));
  console.log(`brand: assets/brand/${name}`);
}

// The server's consent pages show the mark on the graphite app-icon tile: the dark mark.
const brandTs = join(here, '..', '..', 'apps', 'server', 'src', 'brand.ts');
const ts = readFileSync(brandTs, 'utf8');
const next = ts.replace(/export const MARK_SVG = `[^`]*`;/, `export const MARK_SVG = \`${markSvg({ colors: COLORS.dark, id: 'qalm-mark' })}\`;`);
if (next === ts && !ts.includes('export const MARK_SVG')) throw new Error('MARK_SVG not found in apps/server/src/brand.ts');
writeFileSync(brandTs, next);
console.log('brand: apps/server/src/brand.ts MARK_SVG');
