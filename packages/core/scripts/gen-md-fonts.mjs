// Generates the Markdown text boxes' font data from the fonts PageCanvas draws them with
// (modules/qalm-ink/assets/fonts):
//   src/markdown/fontMetrics.ts  advance widths (per 1000 em) of every character each font has, so a box wraps the
//                                same on the page, in PDF exports and in agents' crops, on every platform
//   src/markdown/fontData.ts     the fonts as base64 (PDF export embeds them; Figtree Regular is in export/figtreeFont.ts)
// Run: node packages/core/scripts/gen-md-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const fontkit = require('@pdf-lib/fontkit');
const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, '../../../modules/qalm-ink/assets/fonts');
const out = join(here, '../src/markdown');

/** Font keys: regular, bold, italic, bold italic, mono (code), maths fallback (what Figtree lacks). */
const FONTS = {
  r: 'Figtree-Regular.ttf',
  b: 'Figtree-Bold.ttf',
  i: 'Figtree-Italic.ttf',
  bi: 'Figtree-BoldItalic.ttf',
  m: 'GeistMono-Regular.ttf',
  x: 'NotoSansMath-Subset.ttf',
};

/** Runs of consecutive code points: [first, adv, adv, …]. */
function advances(file) {
  const font = fontkit.create(readFileSync(join(fontsDir, file)));
  const k = 1000 / font.unitsPerEm;
  const cps = [...new Set(font.characterSet)].filter((cp) => cp >= 32 && cp !== 0xfeff).sort((a, b) => a - b);
  const runs = [];
  let run = null;
  for (const cp of cps) {
    const adv = Math.round(font.glyphForCodePoint(cp).advanceWidth * k);
    if (run && cp === run[0] + run.length - 1) run.push(adv);
    else runs.push((run = [cp, adv]));
  }
  return runs;
}

const header = (what) =>
  `// ${what}\n// Generated by packages/core/scripts/gen-md-fonts.mjs from modules/qalm-ink/assets/fonts (SIL OFL 1.1, see the\n// OFL files there). Don't edit by hand.\n`;

let metrics = header('Advance widths (per 1000 em) of the fonts Markdown text boxes use, as runs [first code point, …advances].');
metrics += 'export const FONT_ADVANCES: Record<string, number[][]> = {\n';
for (const [key, file] of Object.entries(FONTS)) metrics += `  ${key}: ${JSON.stringify(advances(file))},\n`;
metrics += '};\n';
writeFileSync(join(out, 'fontMetrics.ts'), metrics);

const b64 = (file) => readFileSync(join(fontsDir, file)).toString('base64').match(/.{1,120}/g).map((l) => `  '${l}',`).join('\n');
let data = header('The fonts Markdown text boxes use beyond Figtree Regular, as base64 (PDF export embeds them).');
for (const key of ['b', 'i', 'bi', 'm', 'x']) data += `export const FONT_${key.toUpperCase()}_B64 = [\n${b64(FONTS[key])}\n].join('');\n`;
writeFileSync(join(out, 'fontData.ts'), data);
console.log('wrote fontMetrics.ts and fontData.ts');
